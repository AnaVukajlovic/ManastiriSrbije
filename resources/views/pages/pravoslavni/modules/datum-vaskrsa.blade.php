<section class="ps-asec">
  <h2>Zašto se datum Vaskrsa menja</h2>
  <p class="ps-ap">
    Vaskrs je pokretan praznik. Njegov datum se određuje prema drevnom crkvenom pravilu (pashaliji),
    koje povezuje prolećnu ravnodnevicu, pun mesec i nedelju.
  </p>
  <ul class="ps-ul">
    <li>Vaskrs se slavi u <strong>nedelju</strong>.</li>
    <li>Datum zavisi od crkvenog računanja proleća i mesečevih faza (pashalni pun mesec).</li>
  </ul>
</section>

<section class="ps-asec">
  <h2>Osnovno pravilo (pojednostavljeno)</h2>
  <p class="ps-ap">
    Vaskrs se slavi prve nedelje posle “pashalnog” punog meseca koji dolazi nakon prolećne ravnodnevice, i uvek nakon jevrejske Pashe.
    Ovo pravilo potiče sa Prvog Vaseljenskog Sabora u Nikeji (325. godine).
  </p>
</section>

<section class="ps-asec">
  <h2>Zašto se razlikuje od zapadnih datuma</h2>
  <p class="ps-ap">
    U praksi, razlika nastaje zbog primene julijanskog kalendara i aleksandrijske pashalije u Pravoslavnoj Crkvi,
    koja se striktno pridržava kanona Nikejskog sabora da se hrišćanski Vaskrs ne može slaviti pre ili na sam dan starozavetne Pashe.
  </p>
</section>

<section class="ps-asec">
  <h2>Šta još “ide” uz Vaskrs</h2>
  <ul class="ps-ul">
    <li><strong>Veliki post</strong> — priprema kroz podvig i duhovno očišćenje.</li>
    <li><strong>Cveti</strong>, <strong>Veliki petak</strong>, <strong>Velika subota</strong> — praznični tok Stradanja i pobede nad smrću.</li>
    <li><strong>Spasovdan</strong> i <strong>Duhovi</strong> — praznici u Vaskršnjem krugu.</li>
  </ul>
</section>