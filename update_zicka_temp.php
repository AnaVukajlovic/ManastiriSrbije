// Provera svih fajlova
$missing = 0;
foreach ($zicka_data as $id => $item) {
    if (!file_exists('public/' . $item['card_image'])) {
        echo "MISSING CARD: {$item['card_image']} (ID: $id)\n";
        $missing++;
    }
    foreach ($item['images'] as $img) {
        if (!file_exists('public/' . $img['image_url'])) {
            echo "MISSING IMG: {$img['image_url']} (ID: $id)\n";
            $missing++;
        }
        if (strpos($img['description'], "\n") !== false || strpos($img['description'], '<br>') !== false) {
            echo "BAD FORMAT DESC in ID: $id\n";
        }
        if (strpos($img['description'], '*Izvor:') === false) {
            echo "MISSING SOURCE in ID: $id: {$img['description']}\n";
        }
    }
}

echo "Provera završena. Nedostaje fajlova: $missing. Ukupno manastira: " . count($zicka_data) . "\n";
